  const STRINGS = { en, es, pt };
  const LOCALES = { en: 'en', es: 'es-ES', pt: 'pt-BR' };
  const HOTEL_LANGUAGE = { 'habbo.es': 'es', 'habbo.com.br': 'pt', 'habbo.com': 'en' };

  let lang = 'en';
  let format = new Intl.NumberFormat(LOCALES.en);
  const num = (n) => format.format(n);

  window.i18n = {
    // Before the hotel is known, the system language is the best guess
    resolve(setting, hotel) {
      if (setting && setting !== 'auto') return setting;
      if (hotel) return HOTEL_LANGUAGE[hotel] ?? 'en';
      const system = navigator.language.slice(0, 2);
      return STRINGS[system] ? system : 'en';
    },
    set(next) {
      lang = STRINGS[next] ? next : 'en';
      format = new Intl.NumberFormat(LOCALES[lang]);
      document.documentElement.lang = LOCALES[lang];
    },
    get lang() {
      return lang;
    },
    t(key, values = {}) {
      const entry = STRINGS[lang][key] ?? en[key];
      if (entry === undefined) return key;
      return typeof entry === 'function' ? entry(values, num) : entry;
    },
    num,
  };
